// Embeds install.sh into the server bundle. Cloudflare Workers have no filesystem,
// so the control plane cannot read install.sh at runtime.
import { readFileSync, writeFileSync } from "node:fs";

const script = readFileSync(new URL("../install.sh", import.meta.url), "utf8");
const out = `// Generated by scripts/embed-install.mjs from install.sh. Do not edit.\nexport const INSTALL_SCRIPT = ${JSON.stringify(script)};\n`;
writeFileSync(new URL("../lib/install-script.generated.ts", import.meta.url), out);
